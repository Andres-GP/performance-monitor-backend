-- Monitoring data model for the Alphaca/TIS strategy registry.
-- All event timestamps are timestamptz and should be normalized to UTC by ingestion.

CREATE TABLE IF NOT EXISTS portfolio (
    id TEXT PRIMARY KEY,
    broker TEXT NOT NULL,
    account_type TEXT,
    daily_dd_limit_pct NUMERIC(8, 4) NOT NULL CHECK (daily_dd_limit_pct > 0 AND daily_dd_limit_pct <= 100),
    total_dd_limit_pct NUMERIC(8, 4) NOT NULL CHECK (total_dd_limit_pct > 0 AND total_dd_limit_pct <= 100),
    broker_hard_limit_pct NUMERIC(8, 4) CHECK (broker_hard_limit_pct IS NULL OR (broker_hard_limit_pct > 0 AND broker_hard_limit_pct <= 100)),
    server_utc_offset_hours NUMERIC(5, 2) CHECK (server_utc_offset_hours IS NULL OR server_utc_offset_hours BETWEEN -14 AND 14),
    server_utc_offset_verified BOOLEAN NOT NULL DEFAULT FALSE,
    config JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT server_utc_offset_verified OR server_utc_offset_hours IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS strategy (
    id TEXT PRIMARY KEY,
    portfolio_id TEXT NOT NULL REFERENCES portfolio(id) ON DELETE RESTRICT,
    strategy_name_prefix TEXT NOT NULL,
    magic BIGINT NOT NULL,
    timeframe TEXT NOT NULL,
    vehicle TEXT NOT NULL,
    direction TEXT NOT NULL CHECK (direction IN ('long', 'short')),
    config JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (portfolio_id, magic)
);

CREATE INDEX IF NOT EXISTS strategy_portfolio_idx ON strategy(portfolio_id);

CREATE TABLE IF NOT EXISTS event_raw (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key TEXT UNIQUE,
    strategy_id TEXT REFERENCES strategy(id) ON DELETE SET NULL,
    source_name TEXT,
    source_magic BIGINT,
    event_type TEXT NOT NULL,
    ts TIMESTAMPTZ,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload JSONB NOT NULL,
    ingest_status TEXT NOT NULL DEFAULT 'received',
    CHECK (ingest_status IN ('received', 'processed', 'rejected'))
);

CREATE INDEX IF NOT EXISTS event_raw_strategy_ts_idx ON event_raw(strategy_id, ts);
CREATE INDEX IF NOT EXISTS event_raw_type_ts_idx ON event_raw(event_type, ts);

CREATE TABLE IF NOT EXISTS trade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id TEXT NOT NULL REFERENCES strategy(id) ON DELETE RESTRICT,
    ticket TEXT,
    symbol TEXT NOT NULL,
    entry_time TIMESTAMPTZ NOT NULL,
    exit_time TIMESTAMPTZ NOT NULL,
    volume NUMERIC(24, 10) NOT NULL CHECK (volume >= 0),
    entry_price NUMERIC(24, 10),
    exit_price NUMERIC(24, 10),
    profit NUMERIC(24, 10) NOT NULL,
    commission NUMERIC(24, 10),
    trade_type TEXT CHECK (trade_type IS NULL OR trade_type IN ('long', 'short')),
    hold_minutes NUMERIC(16, 4),
    pnl_pct_equity NUMERIC(16, 8),
    duration_deviation_minutes NUMERIC(16, 4),
    cashflow_suspected BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (strategy_id, ticket, exit_time)
);

CREATE INDEX IF NOT EXISTS trade_strategy_exit_ts_idx ON trade(strategy_id, exit_time);
CREATE INDEX IF NOT EXISTS trade_strategy_entry_ts_idx ON trade(strategy_id, entry_time);

CREATE TABLE IF NOT EXISTS equity_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id TEXT NOT NULL REFERENCES strategy(id) ON DELETE CASCADE,
    ts TIMESTAMPTZ NOT NULL,
    equity NUMERIC(24, 10) NOT NULL,
    currency TEXT,
    cashflow_suspected BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (strategy_id, ts)
);

CREATE INDEX IF NOT EXISTS equity_sample_strategy_ts_idx ON equity_sample(strategy_id, ts);

CREATE TABLE IF NOT EXISTS daily_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id TEXT REFERENCES strategy(id) ON DELETE CASCADE,
    portfolio_id TEXT REFERENCES portfolio(id) ON DELETE CASCADE,
    ts TIMESTAMPTZ NOT NULL,
    server_date DATE NOT NULL,
    equity NUMERIC(24, 10),
    performance_equity NUMERIC(24, 10),
    peak_equity NUMERIC(24, 10),
    pnl NUMERIC(24, 10),
    pnl_daily_realized NUMERIC(24, 10),
    pnl_weekly_realized NUMERIC(24, 10),
    pnl_monthly_realized NUMERIC(24, 10),
    daily_dd_pct NUMERIC(16, 8),
    total_dd_pct NUMERIC(16, 8),
    max_dd_pct NUMERIC(16, 8),
    trade_count INTEGER NOT NULL DEFAULT 0 CHECK (trade_count >= 0),
    win_rate NUMERIC(8, 4),
    profit_factor NUMERIC(16, 8),
    expectancy_pct NUMERIC(16, 8),
    avg_hold_minutes NUMERIC(16, 4),
    current_loss_streak INTEGER NOT NULL DEFAULT 0 CHECK (current_loss_streak >= 0),
    max_loss_streak INTEGER NOT NULL DEFAULT 0 CHECK (max_loss_streak >= 0),
    rolling_20 JSONB NOT NULL DEFAULT '{}',
    rolling_50 JSONB NOT NULL DEFAULT '{}',
    open_positions_count INTEGER,
    gross_notional_over_equity NUMERIC(16, 8),
    strategy_contribution_30d JSONB NOT NULL DEFAULT '{}',
    correlation_matrix JSONB NOT NULL DEFAULT '[]',
    CHECK ((strategy_id IS NOT NULL AND portfolio_id IS NULL) OR (strategy_id IS NULL AND portfolio_id IS NOT NULL)),
    UNIQUE (strategy_id, server_date),
    UNIQUE (portfolio_id, server_date)
);

CREATE INDEX IF NOT EXISTS daily_stats_strategy_ts_idx ON daily_stats(strategy_id, ts);
CREATE INDEX IF NOT EXISTS daily_stats_portfolio_ts_idx ON daily_stats(portfolio_id, ts);

CREATE TABLE IF NOT EXISTS heartbeat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id TEXT NOT NULL REFERENCES strategy(id) ON DELETE CASCADE,
    ts TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload JSONB NOT NULL DEFAULT '{}'
);

CREATE INDEX IF NOT EXISTS heartbeat_strategy_ts_idx ON heartbeat(strategy_id, ts);

CREATE TABLE IF NOT EXISTS alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_key TEXT NOT NULL,
    strategy_id TEXT REFERENCES strategy(id) ON DELETE CASCADE,
    portfolio_id TEXT REFERENCES portfolio(id) ON DELETE CASCADE,
    severity TEXT NOT NULL CHECK (severity IN ('critical', 'high', 'medium', 'info')),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'ack', 'resolved')),
    first_seen TIMESTAMPTZ NOT NULL,
    last_seen TIMESTAMPTZ NOT NULL,
    count INTEGER NOT NULL DEFAULT 1 CHECK (count > 0),
    context JSONB NOT NULL DEFAULT '{}',
    ack_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (strategy_id IS NULL OR portfolio_id IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS alert_active_strategy_rule_idx
    ON alert(rule_key, strategy_id) WHERE strategy_id IS NOT NULL AND status IN ('open', 'ack');
CREATE UNIQUE INDEX IF NOT EXISTS alert_active_portfolio_rule_idx
    ON alert(rule_key, portfolio_id) WHERE portfolio_id IS NOT NULL AND status IN ('open', 'ack');
CREATE INDEX IF NOT EXISTS alert_strategy_ts_idx ON alert(strategy_id, first_seen);
CREATE INDEX IF NOT EXISTS alert_status_severity_idx ON alert(status, severity, last_seen);

CREATE TABLE IF NOT EXISTS rule_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_key TEXT NOT NULL,
    scope_type TEXT NOT NULL CHECK (scope_type IN ('strategy', 'portfolio')),
    scope_id TEXT NOT NULL,
    last_evaluated_at TIMESTAMPTZ,
    last_notified_at TIMESTAMPTZ,
    consecutive_failures INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    consecutive_passes INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_passes >= 0),
    state JSONB NOT NULL DEFAULT '{}',
    UNIQUE (rule_key, scope_type, scope_id)
);

CREATE TABLE IF NOT EXISTS unregistered_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT,
    source_magic BIGINT,
    first_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    occurrences INTEGER NOT NULL DEFAULT 1 CHECK (occurrences > 0),
    sample_payload JSONB NOT NULL,
    UNIQUE (source_name, source_magic)
);

CREATE INDEX IF NOT EXISTS unregistered_source_last_seen_idx ON unregistered_source(last_seen);

-- Keep normalized monitoring tables inaccessible to anon/authenticated clients.
